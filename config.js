"use strict";

// Загружает .env из корня проекта в process.env (если файла нет - просто
// ничего не делает, не бросает). Адрес сервера/логин бота - это данные
// конкретного развёртывания (и потенциально приватного сервера), поэтому
// они не хардкожены здесь, а берутся из окружения - см. .env.example.
require('dotenv').config({ quiet: true });

module.exports = {
  // Адрес сервера - обязателен для реального подключения (см. проверку
  // в lib/connect.js/lib/connect-raw.js), но намеренно не имеет дефолта
  // здесь: этот модуль требуют и утилиты, которым host не нужен
  // (например, lib/fill-plan.js - только ради maxFillVolume), и падать
  // из-за отсутствующего MC_HOST в них не должно.
  host: process.env.MC_HOST || null,

  // Порт необязателен: null/undefined/'' - port не передаётся в createBot,
  // и minecraft-protocol сам сделает SRV-запрос _minecraft._tcp.<host>,
  // чтобы узнать хост и порт. Если сервер слушает нестандартный порт без
  // SRV-записи, укажи его явно через MC_PORT в .env.
  port: process.env.MC_PORT ? Number(process.env.MC_PORT) : null,

  // Сервер offline-mode, поэтому auth всегда 'offline'
  username: process.env.MC_USERNAME || "Builder",

  // Версия протокола. Для рукопожатия с Forge-сервером соединение
  // всегда выполняется с автоопределением версии (см. lib/connect.js),
  // это поле используется для информации/логов и как fallback.
  version: process.env.MC_VERSION || "1.12.2",

  // Префикс команд в чате, например: "!goto 100 64 200"
  commandPrefix: "!",

  // Пауза между установкой блоков (мс), чтобы сервер не отключил бота
  // за слишком частые действия (anti-cheat / spam-protection)
  placeDelayMs: 1200,

  // Пауза перед переподключением после разрыва связи (мс)
  reconnectDelayMs: 5000,

  // На каком расстоянии от цели бот считает, что дошёл (для команды goto)
  gotoRangeBlocks: 1,

  // Папка со схемами построек (JSON-файлы)
  schemasDir: "./schemas",

  // Лимит троттлинга команд для index-cmd.js/lib/connect-raw.js (команд в секунду)
  commandsPerSecond: 5,

  // Максимальный объём одного /fill (блоков). Протокольный лимит 1.12.2 -
  // 32768 (32*32*32), но большие /fill подвешивают модовый сервер и бота
  // выкидывает по таймауту - поэтому режем боксы заметно мельче лимита.
  maxFillVolume: 4096,

  // Радиус "дальности прорисовки" сервера в блоках, от точки телепорта до
  // края (см. index-cmd.js: телепорт перед стройкой, чтобы сервер догрузил
  // чанки участка). Если габарит схемы/бокса --wipe больше диаметра
  // (2×радиус), стройка режется на зоны со своим /tp перед каждой.
  // Дефолт - консервативные 8 чанков (128 блоков); настраивай под
  // реальный view-distance сервера, если он больше или меньше.
  tpRenderRadiusBlocks: 128,

  // Пауза после подтверждённого /tp (мс), на которую полагаемся как на
  // время догрузки чанков вокруг новой точки - см. index-cmd.js.
  tpChunkLoadWaitMs: 5000,
};
